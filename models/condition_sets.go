package models

// ConditionSetType is the type of a condition set: a user set, the users whose attributes match
// its conditions, such as the users whose age is above 18, or a resource set, the instances of a
// resource whose attributes match them, such as the documents that are not private.
type ConditionSetType string

// The values of ConditionSetType that this version of the SDK knows.
const (
	// ConditionSetTypeUserSet is a set of users, userset: the type of a condition set that a
	// request leaves out.
	ConditionSetTypeUserSet ConditionSetType = "userset"

	// ConditionSetTypeResourceSet is a set of the instances of one resource, resourceset.
	ConditionSetTypeResourceSet ConditionSetType = "resourceset"
)

// Known reports whether t is one of the constants of ConditionSetType, the values that this
// version of the SDK knows.
func (t ConditionSetType) Known() bool {
	switch t {
	case ConditionSetTypeUserSet, ConditionSetTypeResourceSet:
		return true
	default:
		return false
	}
}

// ConditionSetRead is a condition set of an environment, a user set or a resource set, as the API
// returns it.
type ConditionSetRead struct {
	// Key is the set's key, a URL-friendly name such as adults, which a call may give in place of
	// its ID.
	Key string `json:"key"`

	// Type is the set's type, a user set or a resource set, or empty when the reply holds none.
	Type ConditionSetType `json:"type,omitzero"`

	// Autogenerated reports whether the API created the set itself, such as the set that it
	// creates with a role.
	Autogenerated bool `json:"autogenerated,omitzero"`

	// ResourceID is the ID of the resource of a resource set, or empty for a user set, which has
	// no resource.
	ResourceID string `json:"resource_id,omitzero"`

	// ID is the set's ID, a UUID.
	ID string `json:"id"`

	// OrganizationID is the ID of the set's organization.
	OrganizationID string `json:"organization_id"`

	// ProjectID is the ID of the set's project.
	ProjectID string `json:"project_id"`

	// EnvironmentID is the ID of the set's environment.
	EnvironmentID string `json:"environment_id"`

	// CreatedAt is when the set was created.
	CreatedAt Time `json:"created_at"`

	// UpdatedAt is when the set was last changed.
	UpdatedAt Time `json:"updated_at"`

	// Resource is the resource of a resource set, as the API returns it, or nil when the reply
	// holds none, as for a user set.
	Resource *ResourceRead `json:"resource,omitzero"`

	// Name is the set's name.
	Name string `json:"name"`

	// Description is the set's description, or empty when it has none.
	Description string `json:"description,omitzero"`

	// Conditions are the set's conditions, a JSON object of conditions on attributes joined
	// with allOf and anyOf, with values of any JSON type, or nil when the reply holds none.
	Conditions Attributes `json:"conditions,omitzero"`

	// ParentID is the ID of the set's parent set, or empty when it has none.
	ParentID string `json:"parent_id,omitzero"`
}

// ConditionSetCreate is a condition set to create. Key and Name are required, and the request
// always holds them; each other field that is its zero value (false, nil for a map, empty for a
// string) is left out of the request, and the API gives it its default: a user set, not
// autogenerated, without conditions.
type ConditionSetCreate struct {
	// Key is the set's key, a URL-friendly name of letters, digits, - and _, such as adults. It
	// cannot be changed later.
	Key string `json:"key"`

	// Type is the set's type, sent as it is. Empty leaves it out, and the API creates a user set.
	Type ConditionSetType `json:"type,omitzero"`

	// Autogenerated marks the set as one that the API created itself. False leaves it out.
	Autogenerated bool `json:"autogenerated,omitzero"`

	// ResourceID is the key or the ID of the resource of a resource set, such as document, which
	// a resource set needs. A user set takes no resource, so a create of a user set, of the Type
	// ConditionSetTypeUserSet or of an empty Type, with a ResourceID is not valid, and sends no
	// request. Empty leaves it out.
	ResourceID string `json:"resource_id,omitzero"`

	// Name is the set's name.
	Name string `json:"name"`

	// Description is the set's description. Empty leaves it out.
	Description string `json:"description,omitzero"`

	// Conditions are the set's conditions, a JSON object of conditions on attributes joined with
	// allOf and anyOf, such as {"allOf": [{"user.age": {"greater-than": 18}}]}, with values of
	// any JSON type. Nil leaves them out, and an empty map that is not nil sends {}.
	Conditions Attributes `json:"conditions,omitzero"`

	// ParentID is the ID of the set's parent set. Empty leaves it out.
	ParentID string `json:"parent_id,omitzero"`
}

// ConditionSetUpdate is a change to a condition set: the request holds only the fields that it
// sets, and the set keeps the others, so the zero ConditionSetUpdate sends {} and changes nothing.
// Its type and its resource cannot be changed. No field sends null, so an update cannot clear the
// description or the parent of a set.
type ConditionSetUpdate struct {
	// Name is the set's new name. Empty leaves it out, and the set keeps its name.
	Name string `json:"name,omitzero"`

	// Description is the set's new description. Empty leaves it out, and the set keeps its
	// description.
	Description string `json:"description,omitzero"`

	// Conditions are the set's new conditions, which replace its conditions as a whole, with
	// values of any JSON type. Nil leaves them out, and the set keeps its conditions; an empty
	// map that is not nil sends {}.
	Conditions Attributes `json:"conditions,omitzero"`

	// ParentID is the ID of the set's new parent set. Empty leaves it out, and the set keeps its
	// parent.
	ParentID string `json:"parent_id,omitzero"`
}
